-- V1: 초기 스키마 (postgresql). 엔티티(model/*.java)와 일치해야 함 - ddl-auto=validate 로 검증됨

create table anomaly_events (
    ambient_lux float4,
    confirmed_intentional boolean,
    net_displacement float(53),
    orientation_shift float(53),
    pocket_score float(53),
    proximity_near boolean,
    repeat_count_at_report integer not null,
    risk_score float(53) not null,
    screen_interactive boolean,
    id bigint generated by default as identity,
    model_version bigint,
    occurred_at timestamp(6) with time zone,
    received_at timestamp(6) with time zone,
    device_token varchar(255),
    experiment_condition varchar(255),
    label_source varchar(255),
    raw_sensor_window_json text,
    reason varchar(255),
    source varchar(255),
    primary key (id)
);

create table devices (
    test_device boolean not null,
    id bigint generated by default as identity,
    registered_at timestamp(6) with time zone,
    api_key_hash varchar(255) not null,
    device_token varchar(255) not null unique,
    primary key (id)
);

-- 기기별 조회/삭제, 보관기간 정리, 라벨 데이터 증분 export
create index idx_events_device_token on anomaly_events (device_token);
create index idx_events_received_at on anomaly_events (received_at);
create index idx_events_labeled on anomaly_events (confirmed_intentional, id);
